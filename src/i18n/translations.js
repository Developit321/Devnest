export const getTranslation = (lang, key) => {
  const keys = key.split('.')
  let result = translations[lang]
  for (const k of keys) {
    if (result && result[k]) {
      result = result[k]
    } else {
      result = translations['en']
      for (const k2 of keys) {
        if (result && result[k2]) {
          result = result[k2]
        }
      }
      break
    }
  }
  return result || key
}
